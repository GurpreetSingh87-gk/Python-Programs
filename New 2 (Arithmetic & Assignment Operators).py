#              (Arithmetic)                             (Assignment)
# Plus                                        (+)           (+=)
# Minus                                       (-)           (-=)
# Multiply                                    (*)           (*=)
# Exponent                                    (**)          (**=)
# Division {Give value with decimal}          (/)           (/=)
# Floor division {Give value without decimal} (//)          (//=)
# Modulus(Percentage)                         (%)           (%=)

