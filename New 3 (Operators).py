    # Operators :-


# Logical Operator :- In Python, Logical Operators are used to combine conditional statement and
# ----------------    return a boolean value (True or False) based on the logic of the experssions.
#                     Python has three logical operators:- " AND, OR, NOT "


# 1. AND :- It returns 'True' if both conditions are True, otherwise returns False. 
#   -----
#           Example:- a = 10
#                     b = 20
#                     print(a > 5 and b > 15) # True
#                     print(a > 5 and b > 15) # True             


# 2. OR :-  It returns 'False' if both condition are False, otherwise returns True.
#   -----
#           Example:- a = 10
#                     b = 20
#                     print(a > 5 or b > 25) # True
#                     print(a > 15 or b > 25)# False 


# 3. NOT :- It returns 'False' if both condtions is False, otherwise returns True.
#   -----
#           Example:- a = 10
#                     print(a > 5)  # False
#                     print(a > 15) # True


#-------------------------------------------------------------------------------------------------

# Relational Operator :- In Python, Relational Operators are used to compare values. They return
# -------------------    a Boolean value (True or False) based on the condition being evaluated.
#                        These operators are also known as "boolean or comparion" operator.


# 1. [ > ] (It gives output True/False)

# 2. [ < ] (It gives output True/False)

# 3. [ >= ] (It gives output True/False)

# 4. [ <= ] (It gives ouput True/False)

# 5. [ == ] (To check equality or comparion) 

# 6. [ != ] (To check not equality or comparion)


# Example :- a = 10
#            b = 20
#            print(a > b)  # True
#            print(a < b)  # False
#            print(a >= b) # True
#            print(a <= b) # False
#            print(a == b) # False
#            print(a != b) # True

#-------------------------------------------------------------------------------------------------

# Membership Operator :- In Python, Membership Operators are used to test whether a value is a
# -------------------    member of a sequence such as:- string, list, tuple, set or dictionary.
#                        Python provides two membership operators:- "IN, NOT IN"


# 1. IN :- It returns 'True' if the specified value is present in the sequence (list),
#   -----  otherwise returns False.

#          Example:- my_list = [1,2,3,4,5]
#                    print(3 in my_list)  # True
#                    print(10 in my_list) # False


# 2. NOT IN :- It returns 'True' if the specified value is not present in the sequence (list),
#   -------    otherwise returns False.

#              Example:- my_string = "Hello, Python!"
#                        print("Python" in my_string)   # True
#                        print("Java" not in my_string) # True


#-------------------------------------------------------------------------------------------------

# Indentity Operator :- In Python, Indentity Operators are used to compare the memory location of
# ------------------    two objects. There are two indentity operators:- "IS, IS NOT"


# 1. IS :- It returns 'True' if both variables refer to the same object in memory, otherwise
#  -----   retruns False.

#          Example:- a = [1,2,3]
#                    b = a
#                    c = [1,2,3]
#                    print(a is b)     # True (both refer to the same list in memory)
#                    print(a is c)     # False (different objects with the same content)
#                    print(a is not c) # True (because 'a' and 'c' are different objects)


# 2. IS NOT :- It returns 'True' if both variables refer to the different objects in memory,
#   --------   otherwise returns False.

#              Example:- a = [1,2,3]
